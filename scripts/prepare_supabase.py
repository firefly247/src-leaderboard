"""Build a dormant, server-only Supabase schema. No network or source writes.

python scripts/prepare_supabase.py             # regenerate schema
python scripts/prepare_supabase.py --export-csv # optional local public CSV import
"""
import argparse
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAPPING = ROOT / 'supabase' / 'source-map.json'


def identifier(value):
    if not re.fullmatch(r'[a-z_][a-z_0-9]*', value):
        raise ValueError('Invalid identifier')
    return '"' + value + '"'


def literal(value):
    return "'" + str(value).replace("'", "''") + "'"


def catalog():
    mapping = json.loads(MAPPING.read_text(encoding='utf-8'))
    tables = []
    for name, key in mapping['csv'].items():
        with (ROOT / 'data' / (name + '.csv')).open(encoding='utf-8-sig', newline='') as stream:
            columns = next(csv.reader(stream))
        tables.append((name, columns, key))
    for sheet in mapping['sheets'].values():
        tables.append((sheet['table'], sheet['columns'], sheet['key']))
    return mapping, tables


def schema_sql():
    mapping, tables = catalog()
    lines = ['-- Generated by scripts/prepare_supabase.py. Does not migrate or change the live site.',
             '-- All data remains server-only; no browser/member access is granted.', 'begin;']
    for name, columns, key in tables:
        table = 'public.' + identifier('club_' + name)
        definitions = [identifier(c) + (' jsonb not null' if c == 'session_json' else " text not null default ''") for c in columns]
        definitions.append('primary key (' + ', '.join(map(identifier, key)) + ')')
        lines.append('create table ' + table + ' (\n  ' + ',\n  '.join(definitions) + '\n);')
        lines.append('alter table ' + table + ' enable row level security;')
        lines.append('revoke all on table ' + table + ' from public, anon, authenticated;')
        lines.append('grant select, insert, update, delete on table ' + table + ' to service_role;')
    lines.extend([
        '-- A read-only connection probe with no personal data or elevated execution.',
        'create function public.club_connection_status() returns jsonb',
        'language sql stable security invoker set search_path = pg_catalog as $$',
        "  select jsonb_build_object('schemaVersion', " + literal(mapping['schemaVersion']) + ", 'tables', 12);",
        '$$;',
        'revoke all on function public.club_connection_status() from public, anon, authenticated;',
        'grant execute on function public.club_connection_status() to service_role;',
        'commit;', ''
    ])
    return '\n'.join(lines)


def csv_import_sql():
    mapping, tables = catalog()
    catalog_by_name = {name: (columns, key) for name, columns, key in tables}
    statements = ['-- Public CSV data only. Review before running against a staging project.', 'begin;', "set local standard_conforming_strings = on;"]
    for name in mapping['csv']:
        columns, key = catalog_by_name[name]
        seen = set()
        with (ROOT / 'data' / (name + '.csv')).open(encoding='utf-8-sig', newline='') as stream:
            for row in csv.DictReader(stream):
                if None in row or any(row.get(c) is None for c in columns):
                    raise ValueError('Malformed CSV row in ' + name)
                identity = tuple(row[c] for c in key)
                if any(not part for part in identity) or identity in seen:
                    raise ValueError('Missing or duplicate primary key in ' + name)
                seen.add(identity)
                updates = [identifier(c) + '=excluded.' + identifier(c) for c in columns if c not in key]
                action = 'do update set ' + ', '.join(updates) if updates else 'do nothing'
                statements.append('insert into public.' + identifier('club_' + name) + ' (' + ', '.join(map(identifier, columns)) + ') values (' + ', '.join(literal(row[c]) for c in columns) + ') on conflict (' + ', '.join(map(identifier, key)) + ') ' + action + ';')
    return '\n'.join(statements + ['commit;', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--export-csv', action='store_true')
    args = parser.parse_args()
    if args.export_csv:
        output = ROOT / '.local' / 'supabase' / 'public-csv-import.sql'
        content = csv_import_sql()
    else:
        output = ROOT / 'supabase' / 'migrations' / '20261025130000_prepare_club_storage.sql'
        content = schema_sql()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding='utf-8', newline='\n')
    print(str(output.relative_to(ROOT)))
