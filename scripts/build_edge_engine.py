"""Reuse tested club rules in an isolated JS engine, without Google service calls."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'supabase/functions/club-api/engine.mjs'
OMIT = set('doPost dispatch_ json_ properties_ prop_ requireAdmin_ login_ requestSheet_ birthYearSheet_ savePhotoToGitHub_ githubGet_ githubPut_ githubPutBase64_ githubUrl_ githubRawUrl_ githubHeaders_ trainingSheet_ raceLineupSheet_'.split())
STORAGE = set('storageRequestSummary_ storagePackRequest_ storageUnpackRequest_ storageChanges_ storageNormal_ storageDigest_ storageValidate_ storageCsvText_ storageCsvName_ storageCsvGet_ storageCsvPut_ storagePublicData_ storageSheet_'.split())

def functions(text):
    starts = list(re.finditer(r'^function (\w+)\(', text, re.M))
    return [(m.group(1), text[m.start():starts[i+1].start() if i+1<len(starts) else len(text)]) for i,m in enumerate(starts)]

def main():
    code = (ROOT/'apps-script/Code.gs').read_text(encoding='utf-8')
    constants = code[code.index('const REQUEST_SHEET'):code.index('function doPost')]
    parts = [constants, (ROOT/'apps-script/StorageLayout.gs').read_text(encoding='utf-8')]
    for name in ['Code.gs','Training.gs','RaceLineup.gs','StorageSwitch.gs']:
        for fn, body in functions((ROOT/'apps-script'/name).read_text(encoding='utf-8')):
            if fn in OMIT or name=='StorageSwitch.gs' and fn not in STORAGE:
                continue
            body = re.sub(r"\(typeof storageLock_\s*===\s*'function'\s*\?\s*storageLock_\(\)\s*:\s*LockService.getScriptLock\(\)\)", 'storageLock_()', body)
            body = body.replace('SpreadsheetApp.flush();','')
            parts.append(body)
    parts.append((ROOT/'apps-script/RaceLineupPlan.gs').read_text(encoding='utf-8').replace("if(typeof module==='object'&&module.exports)module.exports=RaceLineupPlan;",''))
    prefix = '''// Generated by scripts/build_edge_engine.py; no network, credentials or shared mutable state.
export function createEngine(snapshot, options) {
const original = structuredClone(snapshot.tables);
const StorageContext_ = {tables:structuredClone(snapshot.tables), sheets:{}, dirty:false};
const Utilities = options.utilities;
function storageProvider_(){return 'supabase';}
function storageLock_(){return {waitLock(){},releaseLock(){}};}
function requireAdmin_(){if(!options.admin)throw new Error('관리자 인증이 만료되었습니다.');}
function requestSheet_(){return storageSheet_('REQUEST_LOG');}
function birthYearSheet_(){return storageSheet_('PLAYER_BIRTH_YEARS');}
function trainingSheet_(){return storageSheet_('WEEKEND_TRAINING');}
function raceLineupSheet_(){return storageSheet_('COMPETITION_LINEUPS');}
function githubGet_(path){return storageCsvGet_(path);}
function githubPut_(path,text,message,sha){return storageCsvPut_(path,text,sha);}
function savePhotoToGitHub_(){if(!options.photoUrl)throw new Error('사진 업로드 정보를 확인해 주세요.');return options.photoUrl;}
'''
    text = prefix + '\n'.join(parts) + '''
snapshot.tables.request_log.forEach((r,i)=>{StorageContext_.tables.request_log[i]=storageUnpackRequest_(r);});
const before = structuredClone(StorageContext_.tables);
return {
  dispatch:(action,payload={})=>dispatchCore_(action,payload,''),
  publicData:()=>storagePublicData_(),
  changes:()=>storageChanges_(before,StorageContext_.tables),
  tables:()=>StorageContext_.tables,
};
}
'''
    if re.search(r'UrlFetchApp|SpreadsheetApp|PropertiesService|CacheService|LockService|ContentService', text):
        raise RuntimeError('Google service reference survived extraction')
    text = re.sub(r'(?m)^[ \t]+$', '', text).replace('선수', '회원')
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding='utf-8')
    print(f'Generated {TARGET.relative_to(ROOT)} ({len(text)} characters)')

if __name__=='__main__':main()
